package lu.uni.programming1.lab2.exercise5;

/**
 * Class for Exercise 5
 */
public class DivideAndRule {
    public static void main(String[] args) {
        float div;
        // A
        div = 1 / 2;
        System.out.println("1/2 = " + div);
        // B
        div = 1f / 2;
        System.out.println("1f/2 = " + div);
        // C
        div = 1 / 2f;
        System.out.println("1/2f = " + div);
        // D
        div = 1f * 1 / 2;
        System.out.println("1f*1/2 = " + div);
        // E
        div = 1 / 2 * 1f;
        System.out.println("1/2*1f = " + div);
    }
}
